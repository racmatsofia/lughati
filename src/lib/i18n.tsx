const dicts = { id, en };
export type Lang = keyof typeof dicts;
export type TKey = keyof typeof id;

export function useT() {
  const { settings } = useApp();
  const lang: Lang = settings.lang;
  return useMemo(() => {
    return (key: TKey, vars?: Record<string, string | number>) => {
      let s: string = (dicts[lang] as Record<string, string>)[key] ?? (id as Record<string, string>)[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      }
      return s;
    };
  }, [lang]);
}

/** Terjemahkan tanpa hook (untuk dipakai di luar komponen React). */
export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = (dicts[lang] as Record<string, string>)[key] ?? (id as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
